#!/usr/bin/env python3
"""Generates the Dart design tokens. Usage: generate_tokens.py <tokens.json> <output.dart>"""
import json
import sys

HEADER = "// Generated by scripts/generate_tokens.py. Do not edit.\n\n"


def main():
    tokens = json.load(open(sys.argv[1], encoding="utf-8"))
    lines = [HEADER, "import 'dart:ui';\n\n", "abstract final class ShortedColors {\n"]
    for name, value in tokens["color"].items():
        lines.append(f"  static const {name} = Color(0xFF{value[1:].upper()});\n")
    lines.append("}\n")
    for group, cls in (("space", "ShortedSpace"), ("radius", "ShortedRadius"), ("size", "ShortedSize"), ("breakpoints", "ShortedBreakpoints")):
        lines.append(f"\nabstract final class {cls} {{\n")
        for name, value in tokens[group].items():
            lines.append(f"  static const double {name} = {value};\n")
        lines.append("}\n")
    lines.append("\nabstract final class ShortedMotion {\n")
    for name, value in tokens["motion"].items():
        lines.append(f"  static const {name} = Duration(milliseconds: {value['durationMs']});\n")
    lines.append("}\n")
    open(sys.argv[2], "w", encoding="utf-8").write("".join(lines))


if __name__ == "__main__":
    main()
